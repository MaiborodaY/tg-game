export type GameElementId = keyof GameElementTags;
export type GameElement<Id extends GameElementId> = HTMLElementTagNameMap[GameElementTags[Id]];

export function byId<Id extends GameElementId>(id: Id): GameElement<Id> {
  const element = document.getElementById(id);
  if (!element) throw new Error(`Missing game element: ${id}`);
  // Each ID's tag is owned by the static template and checked alongside this map.
  return element as GameElement<Id>;
}

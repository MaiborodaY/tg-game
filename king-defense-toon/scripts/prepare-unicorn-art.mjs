import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { renderPortrait, PANTHER_RIDER_PALETTES } from './export-recruitment-portraits.mjs';

const sourceRoot = new URL('../../art/brotd-infinity/allies/elves/battle-unicorn/', import.meta.url);
const output = new URL('../assets/unicorn/', import.meta.url);
export const UNICORN_PALETTES = PANTHER_RIDER_PALETTES;
export const UNICORN_BODY_HEIGHT = 70;

// The saddle cloth sits below the mane; frontal cloth is on either side of the chest.
export function isUnicornClothing(rgba, x, y, frame) {
  const [r, g, b, alpha] = rgba;
  const dx = x - frame.rect.x - frame.footAnchor.x, dy = y - frame.rect.y - frame.footAnchor.y;
  const cloth = frame.index < 12 ? dx >= -25 && dx <= -5 && dy >= -41 && dy <= -19
    : Math.abs(dx) >= 12 && Math.abs(dx) <= 24 && dy >= -37 && dy <= -19;
  return alpha > 0 && cloth && g > r * 1.15 && g >= b * .92 && g - r >= 8;
}

export function unicornArtSource(pack) {
  const geometry = {
    layout: { columns: 4, rows: 4 }, bodyHeight: UNICORN_BODY_HEIGHT / 128,
    baselines: pack.frames.map(({ index, rect, footAnchor }) => (rect.y + footAnchor.y - Math.floor(index / 4) * 128) / 128),
    centers: pack.frames.map(({ index, rect, footAnchor }) => (rect.x + footAnchor.x - index % 4 * 128) / 128),
    sourceRects: Object.fromEntries(pack.frames.map(({ index, rect }) => [index, rect])),
  };
  return `import type { SheetArtUrls, SpriteGeometry } from './art-types.ts';
import type { PaletteRank } from './unit-ranks.ts';

// Exact approved frame geometry; generated by scripts/prepare-unicorn-art.mjs.
export const UNICORN_RENDER_HEIGHT = 47;
export const UNICORN_ASSETS: Readonly<Record<PaletteRank, SheetArtUrls>> = Object.freeze({
${UNICORN_PALETTES.map(({ name }, index) => `  ${index + 1}: { sheet: new URL('./assets/unicorn/unicorn-${name}.webp', import.meta.url).href, art: new URL('${index ? `./assets/unicorn/unicorn-${name}-art.webp` : './assets/recruitment/unicorn.webp'}', import.meta.url).href },`).join('\n')}
});
export const UNICORN_GEOMETRY = ${JSON.stringify(geometry, null, 2)} satisfies SpriteGeometry;
`;
}

async function prepare() {
  const pack = JSON.parse(await readFile(new URL('battle-unicorn-512.frames.json', sourceRoot), 'utf8'));
  assert.equal(pack.frames.length, 16); assert.equal(pack.anchorSpace, 'frame-pixels'); assert.equal(pack.impactPose, 2);
  const source = await readFile(new URL(pack.image, sourceRoot));
  const decoded = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  assert.deepEqual([decoded.info.width, decoded.info.height], [512, 512]);
  await mkdir(output, { recursive: true });
  const totals = [];
  for (const { name, rgb } of UNICORN_PALETTES) {
    const pixels = Buffer.from(decoded.data); let changed = 0;
    if (rgb) for (const frame of pack.frames) {
      const { x: left, y: top, width, height } = frame.rect;
      for (let y = top; y < top + height; y++) for (let x = left; x < left + width; x++) {
        const index = (y * 512 + x) * 4;
        if (!isUnicornClothing(pixels.subarray(index, index + 4), x, y, frame)) continue;
        const brightness = pixels[index + 1] / 170;
        for (let channel = 0; channel < 3; channel++) pixels[index + channel] = Math.min(255, Math.round(rgb[channel] * brightness));
        changed++;
      }
    }
    const atlas = rgb ? await sharp(pixels, { raw: decoded.info }).webp({ lossless: true, effort: 6 }).toBuffer() : source;
    await writeFile(new URL(`unicorn-${name}.webp`, output), atlas);
    if (rgb) {
      assert.ok(changed > 100);
      const { rect } = pack.frames[0];
      const cropped = await sharp(pixels, { raw: decoded.info }).extract({ left: rect.x, top: rect.y, width: rect.width, height: rect.height })
        .raw().toBuffer({ resolveWithObject: true });
      const { image } = await renderPortrait(cropped);
      await writeFile(new URL(`unicorn-${name}-art.webp`, output), image);
    }
    totals.push({ name, bytes: atlas.length, changed });
  }
  await writeFile(new URL('../unicorn-art.ts', import.meta.url), unicornArtSource(pack));
  console.log(JSON.stringify(totals));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await prepare();

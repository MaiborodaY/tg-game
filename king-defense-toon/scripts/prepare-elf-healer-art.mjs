import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import sharp from 'sharp';
import { renderPortrait, PANTHER_RIDER_PALETTES } from './export-recruitment-portraits.mjs';

const sourceRoot = new URL('../../art/brotd-infinity/allies/elves/healer/', import.meta.url);
const output = new URL('../assets/elf-healer/', import.meta.url);
export const ELF_HEALER_PALETTES = PANTHER_RIDER_PALETTES;
export const ELF_HEALER_BODY_HEIGHT = 96;

// Restrict recolouring to the lower green robe, preserving hood, face and crystal.
export function isElfHealerClothing(rgba, x, y, frame) {
  const [r, g, b, alpha] = rgba;
  const anchorX = frame.rect.x + frame.footAnchor.x, anchorY = frame.rect.y + frame.footAnchor.y;
  return alpha > 0 && x >= anchorX - 33 && x <= anchorX + 31
    && y >= anchorY - 43 && y <= anchorY - 7
    && g > r * 1.15 && g >= b * .92 && g - r >= 8;
}

export function elfHealerArtSource(pack, pulse) {
  const geometry = {
    layout: { columns: 4, rows: 4 }, bodyHeight: ELF_HEALER_BODY_HEIGHT / 128,
    baselines: pack.frames.map(({ index, rect, footAnchor }) => (rect.y + footAnchor.y - Math.floor(index / 4) * 128) / 128),
    centers: pack.frames.map(({ index, rect, footAnchor }) => (rect.x + footAnchor.x - index % 4 * 128) / 128),
    sourceRects: Object.fromEntries(pack.frames.map(({ index, rect }) => [index, rect])),
  };
  return `import type { SheetArtUrls, SpriteGeometry, SpriteRect } from './art-types.ts';
import type { PaletteRank } from './unit-ranks.ts';
import type { Point } from './field.ts';

// Exact approved frame geometry; generated by scripts/prepare-elf-healer-art.mjs.
export const ELF_HEALER_RENDER_HEIGHT = 35;
export const ELF_HEALER_ASSETS: Readonly<Record<PaletteRank, SheetArtUrls>> = Object.freeze({
${ELF_HEALER_PALETTES.map(({ name }, index) => `  ${index + 1}: { sheet: new URL('./assets/elf-healer/elf-healer-${name}.webp', import.meta.url).href, art: new URL('${index ? `./assets/elf-healer/elf-healer-${name}-art.webp` : './assets/recruitment/elf-healer.webp'}', import.meta.url).href },`).join('\n')}
});
export const ELF_HEALER_GEOMETRY = ${JSON.stringify(geometry, null, 2)} satisfies SpriteGeometry;
// Keep this small optional atlas out of the initial JavaScript download.
export const ELF_HEAL_PULSE_IMAGE_URL = new URL('./assets/elf-healer/elf-healer-pulse.webp?no-inline', import.meta.url).href;
export const ELF_HEAL_PULSE_FRAMES = ${JSON.stringify(pulse.frames.map(({ rect, groundAnchor }) => ({ rect, groundAnchor })), null, 2)} satisfies readonly { rect: SpriteRect; groundAnchor: Point }[];
`;
}

async function prepare() {
  const pack = JSON.parse(await readFile(new URL('elf-healer-512.frames.json', sourceRoot), 'utf8'));
  const pulse = JSON.parse(await readFile(new URL('elf-healer-pulse-128.frames.json', sourceRoot), 'utf8'));
  assert.equal(pack.frames.length, 16); assert.equal(pack.anchorSpace, 'frame-pixels'); assert.equal(pack.healPose, 2);
  assert.equal(pulse.frames.length, 4); assert.equal(pulse.loop, false);
  const source = await readFile(new URL(pack.image, sourceRoot));
  const decoded = await sharp(source).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  assert.deepEqual([decoded.info.width, decoded.info.height], [512, 512]);
  await mkdir(output, { recursive: true });
  const totals = [];
  for (const { name, rgb } of ELF_HEALER_PALETTES) {
    const pixels = Buffer.from(decoded.data); let changed = 0;
    if (rgb) for (const frame of pack.frames) {
      const { x: left, y: top, width, height } = frame.rect;
      for (let y = top; y < top + height; y++) for (let x = left; x < left + width; x++) {
        const index = (y * 512 + x) * 4;
        if (!isElfHealerClothing(pixels.subarray(index, index + 4), x, y, frame)) continue;
        const brightness = pixels[index + 1] / 170;
        for (let channel = 0; channel < 3; channel++) pixels[index + channel] = Math.min(255, Math.round(rgb[channel] * brightness));
        changed++;
      }
    }
    const atlas = rgb ? await sharp(pixels, { raw: decoded.info }).webp({ lossless: true, effort: 6 }).toBuffer() : source;
    await writeFile(new URL(`elf-healer-${name}.webp`, output), atlas);
    if (rgb) {
      assert.ok(changed > 100);
      const { rect } = pack.frames[0];
      const cropped = await sharp(pixels, { raw: decoded.info }).extract({ left: rect.x, top: rect.y, width: rect.width, height: rect.height })
        .raw().toBuffer({ resolveWithObject: true });
      const { image } = await renderPortrait(cropped);
      await writeFile(new URL(`elf-healer-${name}-art.webp`, output), image);
    }
    totals.push({ name, bytes: atlas.length, changed });
  }
  await writeFile(new URL('elf-healer-pulse.webp', output), await readFile(new URL(pulse.image, sourceRoot)));
  await writeFile(new URL('../elf-healer-art.ts', import.meta.url), elfHealerArtSource(pack, pulse));
  console.log(JSON.stringify(totals));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await prepare();

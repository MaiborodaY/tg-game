type BridgeLocaleResolution = Readonly<{
  storedLocale?: unknown;
  telegramLanguageCode?: unknown;
  browserLanguages?: readonly unknown[];
}>;

type BridgeLocaleStorage = Readonly<{
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}>;

export function normalizeBridgeLocale(value: unknown): BridgeLocale | null {
  if (typeof value !== "string") return null;
  const base = value.trim().toLowerCase().replace(/_/g, "-").split("-")[0];
  if (base === "ua") return "uk";
  return BRIDGE_LOCALES.includes(base as BridgeLocale) ? base as BridgeLocale : null;
}

export function resolveBridgeLocale(options: BridgeLocaleResolution = {}): BridgeLocale {
  const candidates = [
    options.storedLocale,
    options.telegramLanguageCode,
    ...(options.browserLanguages ?? []),
  ];
  for (const candidate of candidates) {
    const locale = normalizeBridgeLocale(candidate);
    if (locale) return locale;
  }
  return "ru";
}

export function readStoredBridgeLocale(storage: BridgeLocaleStorage | null | undefined): BridgeLocale | null {
  if (!storage) return null;
  try {
    return normalizeBridgeLocale(storage.getItem(BRIDGE_LOCALE_STORAGE_KEY));
  } catch {
    return null;
  }
}

export function writeStoredBridgeLocale(
  storage: BridgeLocaleStorage | null | undefined,
  locale: BridgeLocale,
): boolean {
  if (!storage) return false;
  try {
    storage.setItem(BRIDGE_LOCALE_STORAGE_KEY, locale);
    return true;
  } catch {
    return false;
  }
}

export function translateBridge(
  locale: BridgeLocale,
  key: BridgeMessageKey,
  params: BridgeTranslationParams = {},
): string {
  const template = MESSAGES[locale]?.[key] ?? RU_MESSAGES[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (placeholder, name: string) => (
    Object.hasOwn(params, name) ? String(params[name]) : placeholder
  ));
}

export function getBridgeCardNoun(
  locale: BridgeLocale,
  count: number,
  grammaticalCase: "count" | "accusative" = "count",
): string {
  const absolute = Math.abs(Math.trunc(Number(count) || 0));
  if (locale === "en") return absolute === 1 ? "card" : "cards";
  const mod10 = absolute % 10;
  const mod100 = absolute % 100;
  if (mod10 === 1 && mod100 !== 11) {
    if (grammaticalCase === "accusative") return locale === "uk" ? "карту" : "карту";
    return locale === "uk" ? "карта" : "карта";
  }
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) {
    return locale === "uk" ? "карти" : "карты";
  }
  return "карт";
}
